import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Astro's static `redirects` render as HTML stubs — a 200 response carrying
// <meta http-equiv="refresh"> and <meta name="robots" content="noindex">.
// Crawlers count every one of those as a noindex page, and a stub's relative
// links resolve against whatever URL it was reached by. Cloudflare Pages reads
// a `_redirects` file from the output directory and answers those paths with a
// real 301 before any HTML is served, so this integration writes one from the
// same `redirects` map in astro.config.mjs. Astro's stubs stay as the fallback
// for `npm run dev` and `astro preview`, which do not read `_redirects`.
//
// Cloudflare `_redirects` matches paths exactly, so each rule is emitted with
// and without its trailing slash. Domain-level sources (www → apex) are not
// supported in this file — that lives in a Cloudflare dashboard Redirect Rule.

export function renderRedirects(redirects) {
  const lines = [
    '# Generated by src/integrations/cloudflare-redirects.mjs from the `redirects` map in astro.config.mjs.',
    '# Do not edit by hand — edit astro.config.mjs and rebuild.',
    '',
  ];
  for (const [source, target] of Object.entries(redirects ?? {})) {
    const destination = typeof target === 'string' ? target : target.destination;
    const status = typeof target === 'string' ? 301 : target.status ?? 301;
    if (!destination || destination === source) continue;
    lines.push(`${source} ${destination} ${status}`);
    if (source.length > 1 && source.endsWith('/')) {
      lines.push(`${source.slice(0, -1)} ${destination} ${status}`);
    }
  }
  return lines.join('\n') + '\n';
}

export default function cloudflareRedirects() {
  let redirects = {};
  return {
    name: 'cloudflare-redirects',
    hooks: {
      'astro:config:done': ({ config }) => {
        redirects = config.redirects ?? {};
      },
      'astro:build:done': async ({ dir, logger }) => {
        const outFile = path.join(fileURLToPath(dir), '_redirects');
        // public/_redirects (if one exists) is copied into dist first; keep it ahead of the generated rules.
        let existing = '';
        try { existing = await fs.readFile(outFile, 'utf8'); } catch {}
        const generated = renderRedirects(redirects);
        await fs.writeFile(outFile, existing ? `${existing.trimEnd()}\n\n${generated}` : generated);
        const count = generated.split('\n').filter((l) => l && !l.startsWith('#')).length;
        logger.info(`Wrote _redirects with ${count} rules.`);
      },
    },
  };
}
